-- 1. DESTINATIONS (Core destination entities)
CREATE TABLE DESTINATIONS (
    ID VARCHAR(64) NOT NULL PRIMARY KEY,
    NAME VARCHAR(255) NOT NULL,
    ALTERNATE_NAMES VARCHAR(500),
    CITY VARCHAR(128),
    DISTRICT VARCHAR(128),
    VILLAGE VARCHAR(128),
    STATE VARCHAR(128) NOT NULL,
    REGION VARCHAR(64) NOT NULL,
    CATEGORY VARCHAR(128) NOT NULL,
    OVERVIEW CLOB,
    DESCRIPTION CLOB,
    HISTORY CLOB,
    LEGEND CLOB,
    ARCHITECTURE CLOB,
    BEST_TIME VARCHAR(255),
    BEST_SEASON VARCHAR(128),
    IDEAL_DURATION VARCHAR(128),
    UNESCO_HERITAGE SMALLINT DEFAULT 0 CHECK (UNESCO_HERITAGE IN (0, 1)),
    AUDIO_TOUR_SUMMARY CLOB,
    TRAVEL_TIPS CLOB,
    MAP_QUERY VARCHAR(255),
    LATITUDE DECIMAL(10, 6),
    LONGITUDE DECIMAL(10, 6),
    PRIMARY_IMAGE VARCHAR(1024),
    BUILT_ERA VARCHAR(128),
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

-- Indexes for fast searching & filtering in Travel Lens AI
CREATE INDEX IDX_DEST_STATE ON DESTINATIONS (STATE);
CREATE INDEX IDX_DEST_REGION ON DESTINATIONS (REGION);
CREATE INDEX IDX_DEST_CATEGORY ON DESTINATIONS (CATEGORY);
CREATE INDEX IDX_DEST_NAME ON DESTINATIONS (NAME);

-- 2. DESTINATION_IMAGES (Gallery photos with cultural captions)
CREATE TABLE DESTINATION_IMAGES (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    DESTINATION_ID VARCHAR(64) NOT NULL,
    IMAGE_URL VARCHAR(1024) NOT NULL,
    CAPTION VARCHAR(500),
    DISPLAY_ORDER SMALLINT DEFAULT 0,
    CONSTRAINT FK_DEST_IMG FOREIGN KEY (DESTINATION_ID)
        REFERENCES DESTINATIONS (ID) ON DELETE CASCADE
);
CREATE INDEX IDX_IMG_DEST ON DESTINATION_IMAGES (DESTINATION_ID);

-- 3. DESTINATION_ATTRACTIONS (Key monuments, temples, viewpoints)
CREATE TABLE DESTINATION_ATTRACTIONS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    DESTINATION_ID VARCHAR(64) NOT NULL,
    ATTRACTION_NAME VARCHAR(255) NOT NULL,
    DETAILS VARCHAR(1000),
    DISPLAY_ORDER SMALLINT DEFAULT 0,
    CONSTRAINT FK_DEST_ATTR FOREIGN KEY (DESTINATION_ID)
        REFERENCES DESTINATIONS (ID) ON DELETE CASCADE
);
CREATE INDEX IDX_ATTR_DEST ON DESTINATION_ATTRACTIONS (DESTINATION_ID);

-- 4. DESTINATION_FOOD (Authentic local dishes, sweets, street food)
CREATE TABLE DESTINATION_FOOD (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    DESTINATION_ID VARCHAR(64) NOT NULL,
    DISH_NAME VARCHAR(255) NOT NULL,
    DISH_DESCRIPTION VARCHAR(1000),
    MUST_TRY_AT VARCHAR(255),
    DISPLAY_ORDER SMALLINT DEFAULT 0,
    CONSTRAINT FK_DEST_FOOD FOREIGN KEY (DESTINATION_ID)
        REFERENCES DESTINATIONS (ID) ON DELETE CASCADE
);
CREATE INDEX IDX_FOOD_DEST ON DESTINATION_FOOD (DESTINATION_ID);

-- 5. DESTINATION_FESTIVALS (Cultural events, Navratri, Aarti, fairs)
CREATE TABLE DESTINATION_FESTIVALS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    DESTINATION_ID VARCHAR(64) NOT NULL,
    FESTIVAL_NAME VARCHAR(255) NOT NULL,
    SEASON VARCHAR(128),
    CONSTRAINT FK_DEST_FEST FOREIGN KEY (DESTINATION_ID)
        REFERENCES DESTINATIONS (ID) ON DELETE CASCADE
);
CREATE INDEX IDX_FEST_DEST ON DESTINATION_FESTIVALS (DESTINATION_ID);

-- 6. DESTINATION_SOURCES (Government tourism & district archive references)
CREATE TABLE DESTINATION_SOURCES (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    DESTINATION_ID VARCHAR(64) NOT NULL,
    SOURCE_TITLE VARCHAR(255) NOT NULL,
    SOURCE_URL VARCHAR(1024) NOT NULL,
    PURPOSE VARCHAR(255),
    CONSTRAINT FK_DEST_SRC FOREIGN KEY (DESTINATION_ID)
        REFERENCES DESTINATIONS (ID) ON DELETE CASCADE
);
CREATE INDEX IDX_SRC_DEST ON DESTINATION_SOURCES (DESTINATION_ID);

-- 7. VARANASI_GHATS (Special 8 Sacred Riverfront Ghats of Kashi Trail)
CREATE TABLE VARANASI_GHATS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    NAME VARCHAR(128) NOT NULL,
    CATEGORY VARCHAR(128) NOT NULL,
    STORY CLOB NOT NULL,
    SIGNIFICANCE CLOB NOT NULL,
    EXPERIENCE CLOB NOT NULL,
    LOCATION VARCHAR(255) NOT NULL,
    IMAGE_URL VARCHAR(1024),
    DISPLAY_ORDER SMALLINT DEFAULT 0
);

-- 8. USER_WISHLISTS (Persistent user bucket list bookmarks)
CREATE TABLE USER_WISHLISTS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    USER_ID VARCHAR(128) NOT NULL,
    DESTINATION_ID VARCHAR(64) NOT NULL,
    NOTES VARCHAR(500),
    SAVED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_WISH_DEST FOREIGN KEY (DESTINATION_ID)
        REFERENCES DESTINATIONS (ID) ON DELETE CASCADE
);
CREATE INDEX IDX_WISH_USER ON USER_WISHLISTS (USER_ID);
